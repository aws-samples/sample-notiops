/** journal 记录 → 时间线条目 HTML（对应 Python `_build_timeline`）。 */
function buildTimeline(records, fetchErrors, locale) {
  const en = locale === "en";
  const entries = [];
  for (const r of records || []) {
    const recordType = r?.recordType ?? "unknown";
    const recordId = String(r?.recordId ?? "");
    let created = r?.createdAt ?? "";
    if (created instanceof Date) created = Number.isNaN(created.getTime()) ? "" : created.toISOString().slice(11, 19);
    else if (typeof created === "string" && created.length > 19) created = created.slice(11, 19);

    const [role, , bodyHtml] = parseRecord(r?.content ?? "", recordType);
    const cssClass = typeToCss(role || recordType);
    const typeLabel = role || recordType || "unknown";
    const collapsed = bodyHtml.length > 500 ? "collapsed" : "";

    entries.push(`
    <div class="entry ${cssClass}">
      <div class="entry-header">
        <span class="entry-type type-${cssClass}">${esc(typeLabel)}</span>
        <span class="entry-time">${esc(created)}</span>
        <span class="entry-id">${esc(recordId.slice(0, 20))}</span>
        ${collapsed ? "<button class='toggle-btn'>expand</button>" : ""}
      </div>
      <div class="entry-body ${collapsed}">
        <pre>${bodyHtml}</pre>
      </div>
    </div>`);
  }
  if (entries.length) return entries.join("\n");

  // 空态：「取失败」与「确实没有」必须是两句不同的话（Python 版注释里有那次现网误读的来龙去脉）。
  if (fetchErrors && fetchErrors.length) {
    const items = fetchErrors.slice(0, 5).map((m) => `      <li>${esc(String(m))}</li>`).join("\n");
    return en
      ? `    <div class="empty">\n      <b>Could not read the investigation records</b> (this is not "the investigation left no records"). The report itself is unaffected; only this page has no data. Reasons:\n      <ul>\n${items}\n      </ul>\n    </div>`
      : `    <div class="empty">\n      <b>无法读取调查记录</b>（不是「本次调查没有记录」）。报告正文不受影响，只有这一页取不到数据。原因：\n      <ul>\n${items}\n      </ul>\n    </div>`;
  }
  return en
    ? '    <div class="empty">\n      This investigation left no step-by-step records (DevOps Agent produced no journal records). See the report page for its conclusions.\n    </div>'
    : '    <div class="empty">\n      本次调查没有留下逐步记录（DevOps Agent 未产出 journal 记录）。调查结论请看「在线查看报告」那一页。\n    </div>';
}

// 只处理 timelineMd 会产出的那几种记号 —— 不是通用 markdown 渲染器（同 Python `_md_lite`）。
const MD_H3_RE = /^(#{3,6})\s+(.*)$/;
const MD_LI_RE = /^[-*]\s+(.*)$/;
const MD_BOLD_RE = /\*\*(.+?)\*\*/g;
const MD_CODE_RE = /`([^`]+)`/g;

/** 受限 markdown → HTML 片段。🔴 先转义再套记号（顺序颠倒就是 XSS）。 */
export function mdLite(md) {
  const text = String(md || "").trim();
  if (!text) return "";
  const out = [];
  let inList = false;
  const inline = (s) => esc(s).replace(MD_BOLD_RE, "<strong>$1</strong>").replace(MD_CODE_RE, "<code>$1</code>");
  const closeList = () => { if (inList) { out.push("</ul>"); inList = false; } };
  for (const line of text.split("\n")) {
    const stripped = line.trim();
    if (!stripped) { closeList(); continue; }
    let m = MD_H3_RE.exec(stripped);
    if (m) { closeList(); out.push(`<h3>${inline(m[2])}</h3>`); continue; }
    m = MD_LI_RE.exec(stripped);
    if (m) {
      if (!inList) { out.push("<ul>"); inList = true; }
      out.push(`<li>${inline(m[1])}</li>`);
      continue;
    }
    closeList();
    out.push(`<p>${inline(stripped)}</p>`);
  }
  closeList();
  return out.join("\n");
}

/** 一条记录的 content → [role, displayType, bodyHtml]（对应 Python `_parse_record`）。 */
function parseRecord(content, recordType) {
  let c = content;
  if (typeof c === "string") {
    try { c = JSON.parse(c); } catch { return [recordType, recordType, esc(c)]; }
  }
  if (!c || typeof c !== "object" || Array.isArray(c)) return [recordType, recordType, esc(pyStr(c))];

  const role = c.role ?? recordType;
  let inner = c.content ?? "";
  if (typeof inner === "string") {
    try { inner = JSON.parse(inner); } catch { return [role, role, esc(inner)]; }
  }

  if (Array.isArray(inner)) {
    const parts = [];
    for (const block of inner) {
      if (!block || typeof block !== "object" || Array.isArray(block)) {
        parts.push(esc(cpSlice(pyStr(block), 1000)));
        continue;
      }
      const btype = block.type ?? "";
      if (btype === "text") {
        parts.push(`<b>[text]</b>\n${esc(block.text ?? "")}`);
      } else if (btype === "thinking") {
        const text = String(block.thinking ?? "");
        if (text) {
          const n = cpLen(text);
          const suffix = n > 2000 ? `\n\n... (${n} chars total)` : "";
          parts.push(`<b>[thinking]</b>\n${esc(cpSlice(text, 2000))}${suffix}`);
        }
      } else if (btype === "tool_use") {
        const name = block.tool_name ?? "unknown";
        parts.push(`<b>[tool_use: ${esc(name)}]</b>\n${esc(pyJson(block.input ?? {}))}`);
      } else if (btype === "tool_result") {
        let rc = block.content ?? "";
        if (Array.isArray(rc)) {
          rc = rc.map((b) => (b && typeof b === "object" && !Array.isArray(b)) ? pyStr(b.text ?? b) : pyStr(b)).join("\n");
        } else if (rc && typeof rc === "object") {
          rc = pyJson(rc);
        }
        let rcStr = pyStr(rc);
        const n = cpLen(rcStr);
        if (n > 10000) rcStr = `${cpSlice(rcStr, 10000)}\n\n... (${n} chars total, truncated)`;
        parts.push(`<b>[tool_result]</b>\n${esc(rcStr)}`);
      } else {
        parts.push(`<b>[${esc(btype)}]</b>\n${esc(pyStr(block))}`);
      }
    }
    return [role, role, parts.join("\n\n")];
  }
  return [role, role, esc(pyJson(c))];
}

/** 记录类型 / 角色 → CSS class（对应 Python `_type_to_css`）。 */
function typeToCss(t) {
  const s = String(t ?? "").toLowerCase();
  if (s === "user") return "user";
  if (s === "assistant") return "assistant";
  if (s.includes("tool_use") || s.includes("tool-use")) return "tool-use";
  if (s.includes("tool_result") || s.includes("tool-result")) return "tool-result";
  if (s.includes("thinking")) return "thinking";
  if (s.includes("system")) return "system";
  return "other";
}

