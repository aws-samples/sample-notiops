/**
 * 编译期功能开关 —— 「实现留着、入口先关掉」的那一类。
 *
 * 与 `/admin/modules`（模块开关）的区别，别混：那一套是**客户自己**在管理后台按部署打开
 * 或关闭的运行期配置，会读 DDB、每个部署可以不一样。这里这一份是**我们**在发版时决定的
 * 编译期常量 —— 客户看不到、也改不了。用它的场合只有一种：某条链路的代码要完整保留
 * （以后可能启用），但当前不希望它出现在任何客户可见的界面上。
 *
 * 为什么不直接把代码删掉:删了以后重新启用等于重写一遍(以及重新踩一遍已经踩过的坑)。
 * 为什么不做成运行期开关:那会变成一个「客户能自己打开的未完成功能」,还要为它维护
 * 后端路由、权限和文档 —— 而我们此刻想要的恰恰相反。
 *
 * ── 加一个开关时的三条要求 ──────────────────────────────────────────────────
 *  1. **常量必须是 `false | true` 字面量**，不要读环境变量。两条部署路径（方式 A 一键
 *     CloudFormation / 方式 B `setup.sh`）共用同一份 `chat-app/dist` 产物，编译期常量
 *     天然对等；一旦改成读 env，两条路径就可能出现"一边有一边没有"，而这正是本仓库的铁律
 *     （新功能/改动必须两条路径同时支持）要挡的东西。
 *  2. **把所有消费点列在开关的注释里**。关一个入口通常要同时关"选择器 / 主题闸门 / 管理页
 *     导航"好几处，漏一处的症状是"界面上还剩半个入口"，而且没有任何报错。
 *  3. IM 侧有**另一份**同名开关（`core/multicloud.py`），因为那是 Python 的另一个进程。
 *     两边要一起翻，否则会出现「网页里没有、IM 里还在推荐」这种自相矛盾的产品。
 */

/**
 * 多云（客户自己的阿里云 STAROps 数字员工）在 **Web 端**的可见性。
 *
 * `false` = 全部入口隐藏，实现代码原样保留（BFF 路由、`starops_chat`、DDB 会话段、
 * i18n 文案、测试全都还在，翻成 `true` 就整套回来）。
 *
 * 消费点（改这个常量必须把这几处一起看一遍）：
 *  · `types.ts::topicHasStarops` —— 主题闸门。回 `false` 会让 `convMode.restorableMode`
 *    把已落盘的 `"starops"` 一并当"这个主题不提供这个模式"丢掉，所以**老会话不会**
 *    恢复出一个界面上看不见的对象（这正是那个函数文件头写的「开着一个界面上根本没有的
 *    开关」）。
 *  · `components/ChatObjectPicker.tsx` —— 新对话主页那一排「对话对象」里的 STAROps 段，
 *    连同它那次 `/features/starops` 探测请求（关了就别打，省一个签名请求）。
 *  · `components/AdminPanel.tsx` —— 「云环境」组里的「多云」导航项。`AliyunView` /
 *    `AliyunGuideDrawer` 的代码保留，只是没有入口能走到。
 *
 * 不在消费点里、**有意保留**的两处：
 *  · `types.ts::CONV_OBJECTS` 里的 `starops` 标签 —— 侧栏那一格是**只读展示**。已经存在的
 *    STAROps 会话（现网上真的有）还要能正确显示成 STAROps；跟着藏掉的话它们会退成
 *    "没有标签"或者被误显示成 DevOps，那是**改写既有事实**，比多一个标签糟得多。
 *  · BFF 的 `/features/starops` 与 STAROps 那条对话链路 —— 后端一律不动。前端不去调而已。
 */
